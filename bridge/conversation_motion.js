/* Springs sampled once and handed to Web Animations. Settled elements retain
   their normal styles, and the Reader only follows height changes per frame. */
(function(root){
  'use strict';
  function stepSpring(state,target,stiffness,damping,seconds){
    const dt=Math.min(seconds,1/30)/4;
    for(let i=0;i<4;i++){
      state.velocity+=(stiffness*(target-state.value)-damping*state.velocity)*dt;
      state.value+=state.velocity*dt;
    }
    return state.value;
  }
  function spring(stiffness,damping){
    const state={value:0,velocity:0},values=[0];
    do{values.push(stepSpring(state,1,stiffness,damping,1/60));}
    while(Math.abs(1-state.value)>.002||Math.abs(state.velocity)>.02);
    values.push(1);
    return values;
  }
  const bounded=value=>Math.min(1,Math.max(0,value));
  const WORD=70,wordFrames=spring(340,26).map(value=>({
    top:(1-value)*6+'px',filter:`blur(${(1-bounded(value))*4}px)`,opacity:bounded(value),
  }));
  const promptFrames=spring(300,22).map(value=>({
    transform:`translateY(${(1-value)*14}px) scale(${.92+.08*value})`,opacity:bounded(value),
  }));
  const heights=spring(260,26);
  const eastAsian=/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\u3001\u3002\uff01\uff1f\uff1b\uff0c\uff0e\u2026]/u;
  const punctuation=/[\u3001\u3002\uff01\uff1f\uff1b\uff0c\uff0e\u2026]/u;
  const graphemes=typeof Intl.Segmenter==='function'?new Intl.Segmenter('ja',{granularity:'grapheme'}):null;
  function pieces(text){
    const segments=/\s+|[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\u3001\u3002\uff01\uff1f\uff1b\uff0c\uff0e\u2026]+|[^\s\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\u3001\u3002\uff01\uff1f\uff1b\uff0c\uff0e\u2026]+/gu;
    return (text.match(segments)||[]).flatMap(run=>{
      if(!eastAsian.test(run))return [run];
      const chars=graphemes?Array.from(graphemes.segment(run),part=>part.segment):Array.from(run);
      const groups=[];let part='',count=0;
      for(const character of chars){
        part+=character;count++;
        if(count===4||punctuation.test(character)){groups.push(part);part='';count=0;}
      }
      if(part)groups.push(part);
      return groups;
    });
  }
  // These two headers are generated by the delegated launcher. Match the
  // child and the known parent as well as the fixed part of the envelope.
  function promptAuthor(text,name,parent){
    if(!name||!parent)return '';
    const embedded=`\u3042\u306a\u305f\u306f ${name}\uff08\u89aa: ${parent}\uff09\u3002\u3053\u306e\u8d77\u52d5\u306f --embed-task mode \u3067\u3059\u3002ORRERY Mail \u3078\u306e\u767b\u9332\u306f\u89aa\u304c\u5b8c\u4e86\u6e08\u307f\u30fb\u5100\u5f0f\u4e0d\u8981\u3067\u3059\u3002`;
    const delegated=`You are ${name}. The parent agent is ${parent}. The child name ${name} is already reserved, so do not register under another name.`;
    return text.startsWith(embedded)||text.startsWith(delegated)?parent:'';
  }
  function mount({visible,follow}){
    const reduced=root.matchMedia('(prefers-reduced-motion: reduce)');
    const animations=new Set(),replyAnimations=new Set();
    let wordTime=0,frame=0,heightAnimation=null,following=false,body=null,parts=[];
    const allowed=()=>visible()&&!reduced.matches;
    function animate(element,frames,{delay=0,group=null}={}){
      if(!allowed())return null;
      const animation=element.animate(frames,{duration:(frames.length-1)*1000/60,delay,fill:'backwards'});
      animations.add(animation);group?.add(animation);
      const remove=()=>{animations.delete(animation);group?.delete(animation);};
      animation.finished.then(remove,remove);
      return animation;
    }
    function stopReply(){
      for(const animation of replyAnimations)animation.cancel();
      replyAnimations.clear();cancelAnimationFrame(frame);
      frame=0;heightAnimation=null;following=false;wordTime=0;body=null;parts=[];
    }
    function stop(){
      stopReply();for(const animation of animations)animation.cancel();animations.clear();
    }
    function grow(previous,target,keepBottom){
      heightAnimation?.cancel();cancelAnimationFrame(frame);frame=0;heightAnimation=null;
      if(!keepBottom||previous>=target-.5)return;
      const animation=animate(body,heights.map(value=>({height:previous+(target-previous)*value+'px'})),{group:replyAnimations});
      if(!animation)return;
      heightAnimation=animation;following=keepBottom;
      const update=()=>{
        frame=0;
        if(heightAnimation!==animation)return;
        if(following)follow();
        if(animation.playState==='running'||animation.pending)frame=requestAnimationFrame(update);
      };
      if(following)frame=requestAnimationFrame(update);
      const release=()=>{if(heightAnimation===animation){heightAnimation=null;if(following)follow();}};
      animation.finished.then(release,release);
    }
    function write(element,text,{seen=0,keepBottom=false,plain=false}={}){
      if(element!==body){stopReply();body=element;}
      if(plain||!allowed()){
        stopReply();
        const node=element.firstChild;
        if(node?.nodeType===3&&element.childNodes.length===1)node.data=text;
        else element.textContent=text;
        return;
      }
      const before=body.getBoundingClientRect().height;
      heightAnimation?.cancel();
      const next=pieces(text);
      if(!parts.length)body.replaceChildren();
      // A provider often extends the last partial word on its next frame.
      // Keep its element and its original animation.
      const tail=parts.length-1;
      if(tail>=0&&next[tail]!==parts[tail])body.lastChild.textContent=next[tail];
      let offset=parts.join('').length+(tail>=0?next[tail].length-parts[tail].length:0);
      const fragment=document.createDocumentFragment(),now=performance.now();
      // A delayed terminal batch can contain many words. Paint the earliest
      // ones immediately and retain at most a second of stagger.
      const motionStart=Math.max(parts.length,next.length-24);
      for(let index=parts.length;index<next.length;index++){
        const value=next[index],start=offset;offset+=value.length;
        if(!value.trim()){fragment.append(value);continue;}
        const word=document.createElement('span');word.className='conversation-stream-word';word.textContent=value;fragment.append(word);
        if(start<seen||index<motionStart)continue;
        const delay=Math.max(0,wordTime-now);
        if(delay>980)continue;
        animate(word,wordFrames,{delay,group:replyAnimations});wordTime=now+delay+WORD;
      }
      body.append(fragment);parts=next;
      const target=body.getBoundingClientRect().height;
      const firstLine=parseFloat(getComputedStyle(body).lineHeight)||target;
      grow(before||Math.min(firstLine,target),target,keepBottom);
    }
    reduced.addEventListener('change',stop);
    return {
      write,stopReply,stop,stopFollowing(){following=false;heightAnimation?.cancel();},
      prompt:element=>animate(element,promptFrames),
      dispose(){stop();reduced.removeEventListener('change',stop);},
    };
  }
  root.OrreryConversationMotion=Object.freeze({mount,stepSpring,pieces,promptAuthor});
})(typeof window!=='undefined'?window:globalThis);
